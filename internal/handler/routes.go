package handler

import "net/http"

func (a *App) routes(mux *http.ServeMux) {
	mux.HandleFunc("GET /healthz", a.healthz)
	mux.Handle("GET /static/", http.StripPrefix("/static/", a.staticHandler()))
	mux.HandleFunc("GET /media/{key...}", a.publicMedia)
	mux.HandleFunc("GET /sitemap.xml", a.sitemap)
	mux.HandleFunc("GET /robots.txt", a.robots)
	mux.HandleFunc("GET /site.webmanifest", a.webmanifest)
	mux.HandleFunc("GET /favicon.ico", a.faviconICO)

	mux.HandleFunc("GET /{$}", a.home)
	mux.HandleFunc("GET /sessions", a.sessionsList)
	mux.HandleFunc("GET /sessions/{slug}", a.sessionShow)
	mux.HandleFunc("POST /sessions/{slug}/registrations", a.sessionJoin)
	mux.HandleFunc("GET /sessions/{slug}/rotation", a.rotationBoard)
	mux.HandleFunc("GET /tickets/{token}", a.ticketShow)
	mux.HandleFunc("POST /tickets/{token}/payment-proofs", a.ticketUpload)
	mux.HandleFunc("POST /tickets/{token}/cancel", a.ticketCancel)
	mux.HandleFunc("POST /tickets/{token}/transfer", a.ticketTransfer)
	mux.HandleFunc("POST /tickets/{token}/refund-account", a.ticketRefundAccount)
	mux.HandleFunc("GET /tickets/{token}/uploads/{id}", a.ticketProofImage)
	mux.HandleFunc("GET /announcements", a.announcements)
	mux.HandleFunc("GET /leaderboard", a.leaderboard)
	mux.HandleFunc("GET /login", a.loginForm)
	mux.HandleFunc("POST /login", a.loginSubmit)
	mux.HandleFunc("GET /register", a.registerForm)
	mux.HandleFunc("POST /register", a.registerSubmit)
	mux.HandleFunc("POST /logout", a.logout)

	member := a.requireMember
	mux.Handle("GET /me", member(a.meShow))
	mux.Handle("GET /me/registrations", member(a.meRegistrations))
	mux.Handle("POST /me/registrations/{id}/payment-proofs", member(a.meUpload))
	mux.Handle("POST /me/registrations/{id}/cancel", member(a.meCancel))
	mux.Handle("POST /me/registrations/{id}/transfer", member(a.meTransfer))
	mux.Handle("POST /me/registrations/{id}/refund-account", member(a.meRefundAccount))
	mux.Handle("GET /me/uploads/{id}", member(a.meProofImage))
	mux.Handle("POST /me/profile", member(a.meProfile))
	mux.Handle("GET /me/password", member(a.mePasswordForm))
	mux.Handle("POST /me/password", member(a.mePasswordSubmit))

	admin := a.requireAdmin
	mux.Handle("GET /admin", admin(a.adminDashboard))
	mux.Handle("GET /admin/leaderboard", admin(a.adminLeaderboard))

	mux.Handle("GET /admin/venues", admin(a.adminVenues))
	mux.Handle("POST /admin/venues", admin(a.adminVenueSave))
	mux.Handle("POST /admin/venues/{id}", admin(a.adminVenueSave))
	mux.Handle("POST /admin/venues/{id}/delete", admin(a.adminVenueDelete))

	mux.Handle("GET /admin/templates", admin(a.adminTemplates))
	mux.Handle("GET /admin/templates/new", admin(a.adminTemplateForm))
	mux.Handle("GET /admin/templates/{id}", admin(a.adminTemplateForm))
	mux.Handle("POST /admin/templates", admin(a.adminTemplateSave))
	mux.Handle("POST /admin/templates/{id}", admin(a.adminTemplateSave))
	mux.Handle("POST /admin/templates/{id}/delete", admin(a.adminTemplateDelete))
	mux.Handle("POST /admin/templates/{id}/sessions", admin(a.adminTemplateCreateSession))

	mux.Handle("GET /admin/sessions", admin(a.adminSessions))
	mux.Handle("GET /admin/sessions/new", admin(a.adminSessionForm))
	mux.Handle("POST /admin/sessions", admin(a.adminSessionSave))
	mux.Handle("GET /admin/sessions/{id}", admin(a.adminSessionShow))
	mux.Handle("GET /admin/sessions/{id}/edit", admin(a.adminSessionForm))
	mux.Handle("POST /admin/sessions/{id}", admin(a.adminSessionSave))
	mux.Handle("POST /admin/sessions/{id}/publish", admin(a.adminSessionPublish))
	mux.Handle("POST /admin/sessions/{id}/close", admin(a.adminSessionClose))
	mux.Handle("POST /admin/sessions/{id}/cancel", admin(a.adminSessionCancel))
	mux.Handle("POST /admin/sessions/{id}/delete", admin(a.adminSessionDelete))
	mux.Handle("POST /admin/sessions/{id}/costs", admin(a.adminSessionCosts))
	mux.Handle("GET /admin/sessions/{id}/broadcast", admin(a.adminBroadcast))
	mux.Handle("POST /admin/sessions/{id}/registrations", admin(a.adminAddRegistration))
	mux.Handle("GET /admin/sessions/{id}/game-day", admin(a.adminGameDay))
	mux.Handle("POST /admin/sessions/{id}/rotation-rounds", admin(a.adminRotationNext))
	mux.Handle("POST /admin/sessions/{id}/rotation-rounds/undo", admin(a.adminRotationUndo))
	mux.Handle("POST /admin/sessions/{id}/rotation-rounds/swap", admin(a.adminRotationSwap))

	mux.Handle("POST /admin/registrations/{id}/move", admin(a.adminRegMove))
	mux.Handle("POST /admin/registrations/{id}/attendance", admin(a.adminRegAttendance))
	mux.Handle("POST /admin/registrations/{id}/mark-paid", admin(a.adminRegMarkPaid))
	mux.Handle("POST /admin/registrations/{id}/cancel", admin(a.adminRegCancel))
	mux.Handle("POST /admin/registrations/{id}/delete", admin(a.adminRegDelete))
	mux.Handle("POST /admin/registrations/{id}/level", admin(a.adminRegLevel))

	mux.Handle("GET /admin/payments", admin(a.adminPayments))
	mux.Handle("POST /admin/payment-proofs/{id}/approve", admin(a.adminProofApprove))
	mux.Handle("POST /admin/payment-proofs/{id}/reject", admin(a.adminProofReject))
	mux.Handle("GET /admin/refunds", admin(a.adminRefunds))
	mux.Handle("POST /admin/refunds/{id}/complete", admin(a.adminRefundComplete))
	mux.Handle("GET /admin/uploads/{id}", admin(a.adminProofImage))

	mux.Handle("GET /admin/finance", admin(a.adminFinance))
	mux.Handle("GET /admin/finance/export.csv", admin(a.adminFinanceCSV))

	mux.Handle("GET /admin/announcements", admin(a.adminAnnouncements))
	mux.Handle("POST /admin/announcements", admin(a.adminAnnouncementSave))
	mux.Handle("POST /admin/announcements/{id}", admin(a.adminAnnouncementSave))
	mux.Handle("POST /admin/announcements/{id}/delete", admin(a.adminAnnouncementDelete))

	mux.Handle("GET /admin/members", admin(a.adminMembers))
	mux.Handle("POST /admin/members/{id}", admin(a.adminMemberSave))
	mux.Handle("POST /admin/members/{id}/reset-password", admin(a.adminMemberReset))

	mux.Handle("GET /admin/settings", admin(a.adminSettingsIndex))
	mux.Handle("GET /admin/settings/storage", admin(a.adminStorage))
	mux.Handle("GET /admin/settings/{group}", admin(a.adminSettings))
	mux.Handle("POST /admin/settings/{group}", admin(a.adminSettingsSave))

	mux.Handle("GET /admin/pages", admin(a.adminPages))
	mux.Handle("GET /admin/pages/new", admin(a.adminPageForm))
	mux.Handle("GET /admin/pages/{id}", admin(a.adminPageForm))
	mux.Handle("POST /admin/pages", admin(a.adminPageSave))
	mux.Handle("POST /admin/pages/{id}", admin(a.adminPageSave))
	mux.Handle("POST /admin/pages/{id}/delete", admin(a.adminPageDelete))
	mux.Handle("POST /admin/pages/{id}/preview", admin(a.adminPagePreview))

	mux.Handle("GET /admin/faq", admin(a.adminFAQ))
	mux.Handle("POST /admin/faq", admin(a.adminFAQSave))
	mux.Handle("POST /admin/faq/reorder", admin(a.adminFAQReorder))
	mux.Handle("POST /admin/faq/{id}", admin(a.adminFAQSave))
	mux.Handle("POST /admin/faq/{id}/delete", admin(a.adminFAQDelete))

	mux.Handle("GET /admin/hero-slides", admin(a.adminHeroSlides))
	mux.Handle("GET /admin/hero-slides/new", admin(a.adminHeroForm))
	mux.Handle("GET /admin/hero-slides/{id}", admin(a.adminHeroForm))
	mux.Handle("POST /admin/hero-slides", admin(a.adminHeroSave))
	mux.Handle("POST /admin/hero-slides/reorder", admin(a.adminHeroReorder))
	mux.Handle("POST /admin/hero-slides/{id}", admin(a.adminHeroSave))
	mux.Handle("POST /admin/hero-slides/{id}/delete", admin(a.adminHeroDelete))

	mux.HandleFunc("GET /{slug}", a.staticPage)
}
